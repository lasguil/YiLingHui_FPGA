#!/usr/bin/env python3
"""Extract fail-closed MJPEG link glue from the real gesture_board_top."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TMP_ROOT = (ROOT / "tmp").resolve()
TOP = ROOT / "rtl" / "gesture_board_top.v"


def count_exact(text: str, needle: str, expected: int = 1) -> None:
    actual = text.count(needle)
    if actual != expected:
        raise SystemExit(
            f"extractor fail-closed: marker {needle!r} count={actual}, expected={expected}"
        )


def between(source: str, start: str, end: str) -> str:
    count_exact(source, start)
    count_exact(source, end)
    i = source.index(start)
    j = source.index(end, i + len(start))
    if j <= i:
        raise SystemExit(f"extractor fail-closed: end marker precedes start marker: {start!r}")
    return source[i:j]


def output_path(value: str) -> Path:
    out = Path(value)
    if not out.is_absolute():
        out = ROOT / out
    resolved = out.resolve()
    if not resolved.is_relative_to(TMP_ROOT):
        raise SystemExit(f"extractor fail-closed: --out must be inside {TMP_ROOT}: {resolved}")
    if resolved.suffix.lower() not in {".sv", ".v"}:
        raise SystemExit("extractor fail-closed: --out must use a .sv or .v suffix")
    return resolved


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", required=True,
        help="generated probe output, required to be under this project's tmp directory",
    )
    args = parser.parse_args()
    out = output_path(args.out)

    source = TOP.read_text(encoding="utf-8")
    source_hash = hashlib.sha256(source.encode()).hexdigest()
    segments = [
        between(source,
                "wire mjpeg_jpg_ready=mjpeg_stream_up[1]&&!mjpeg_fifo_full;",
                "always @(posedge net_a_cmd_clk or negedge net_reset_n)\n    if(!net_reset_n)mjpeg_start_toggle_q"),
        between(source,
                "always @(posedge net_a_cmd_clk or negedge net_reset_n)\n    if(!net_reset_n)mjpeg_start_toggle_q",
                "// Count completed HDMI-source frames in the network clock domain."),
        between(source,
                "axi_init u_mjpeg_axi_init(",
                "always @(posedge proc_clk or negedge proc_reset_n)\n    if(!proc_reset_n)mjpeg_overflow_sticky"),
        between(source,
                "always @(posedge proc_clk or negedge proc_reset_n)\n    if(!proc_reset_n)mjpeg_overflow_sticky",
                "always @(posedge net_a_cmd_clk or negedge net_stream_reset_n)\n    if(!net_stream_reset_n)begin"),
        between(source,
                "always @(posedge net_a_cmd_clk or negedge net_stream_reset_n)\n    if(!net_stream_reset_n)begin",
                "assign net_frame_count=mjpeg_source_frame_count;"),
    ]
    glue = "\n".join(segments)

    # Only scale the test image and FIFO depth; all extracted handshake/FSM
    # source remains verbatim. Every substitution is exact-count checked.
    for old, new in (
        (".IMG_WIDTH(1280),.IMG_HEIGHT(720)", ".IMG_WIDTH(REC_W),.IMG_HEIGHT(REC_H)"),
        (".ADDR_W(13)", ".ADDR_W(FIFO_AW)"),
    ):
        count_exact(glue, old)
        glue = glue.replace(old, new)

    header = f'''// Generated by tools/extract_mjpeg_link_glue.py from rtl/gesture_board_top.v.
// SHA256(top source)={source_hash}
// Extracted logic is verbatim except test-only IMG_WIDTH/HEIGHT and FIFO ADDR_W.
`timescale 1ns/1ps
module mjpeg_top_glue_probe #(
    parameter integer REC_W = 32,
    parameter integer REC_H = 16,
    parameter integer FIFO_AW = 5
) (
    input wire proc_clk, net_a_cmd_clk, rxc,
    input wire proc_reset_n, net_reset_n, net_stream_reset_n,
    input wire net_begin,
    input wire [23:0] mjpeg_rgb,
    input wire mjpeg_src_tvalid, mjpeg_src_tlast, mjpeg_src_tuser,
    input wire mjpeg_source_overflow, mjpeg_source_error,
    input wire net_pop,
    output wire mjpeg_src_tready,
    output wire mjpeg_jpg_valid, mjpeg_jpg_last,
    output wire [7:0] mjpeg_jpg_byte,
    output wire mjpeg_jpg_ready_o, encoder_init_done_o,
    output wire mjpeg_start_pulse,
    output reg mjpeg_frame_active,
    output reg mjpeg_link_abort,
    output wire mjpeg_fifo_full, mjpeg_fifo_empty, mjpeg_fifo_write_empty,
    output wire [8:0] mjpeg_fifo_data,
    output wire net_error, net_busy,
    output wire [8:0] net_pixel,
    output wire net_pixel_valid
);
wire encoder_init_done;
wire [4:0] enc_awaddr, enc_araddr;
wire enc_awvalid, enc_awready, enc_wvalid, enc_wready, enc_bvalid, enc_bready;
wire [31:0] enc_wdata, enc_rdata;
wire [3:0] enc_wstrb;
wire [1:0] enc_bresp, enc_rresp;
wire enc_arvalid, enc_arready, enc_rvalid, enc_rready;
reg mjpeg_overflow_sticky;
(* async_reg="true" *) reg [1:0] mjpeg_stream_up;
reg mjpeg_start_toggle_q;
wire mjpeg_start_toggle;
(* async_reg="true" *) reg [2:0] mjpeg_start_sync;
(* async_reg="true" *) reg [1:0] mjpeg_error_sync,mjpeg_busy_sync;
(* async_reg="true" *) reg [1:0] mjpeg_source_overflow_sync,mjpeg_source_error_sync;
(* async_reg="true" *) reg [1:0] mjpeg_output_overflow_sync;
wire net_available;
assign mjpeg_start_pulse=mjpeg_start_sync[2]^mjpeg_start_sync[1];
'''
    footer = '''
assign mjpeg_jpg_ready_o=mjpeg_jpg_ready;
assign encoder_init_done_o=encoder_init_done;
endmodule
'''

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + glue + footer, encoding="utf-8")
    print(f"generated {out}")
    print(f"top_sha256={source_hash}")
    print("extracted_segments=" + ",".join(str(len(s.splitlines())) for s in segments))


if __name__ == "__main__":
    main()
