// 协议契约：1024×256字，两个512字半区，每半区各一读一写；端口0/1分别对应低/高半区。
// rd_valid[g]=1的时钟沿接受rd_idx[g]，OUTPUT_REG=0，沿后给出该次读数据；没有额外返回有效位。
// rd_valid[g]=0时物理RE=0，读地址及返回原生保持；即使写口改写同址，已有返回仍保持。
// 恢复RE后按新读地址刷新返回；此保持能力是D删除宽数据缓存的前提，不得把RE改回常开。
// wr_valid[g]=1时写入完整256位字；同半区可不同址读写，同拍同址读写遵循READ_FIRST返回旧值。
// RAM与返回不复位，reset仅保留公共接口；控制器必须用valid和真实行标签屏蔽未初始化数据。
// C16配对由结果整理器完成，本模块没有半字写、配对或行提交逻辑。
// ============================================================================
// 激活存储的一片：1024 字 × 256 位（主 Spec §6.1 里那个"逻辑 bank"，四片 A/B/C/D 结构相同）。
//
// ------------------------------ 为什么是"两组" ------------------------------
// 一片 1024×256 恰好 262,144 位 = 25.6 个 10Kbit 块 → 26 个 RAM10。
// 按要求不靠 FIFO 拿带宽，而是把这 26 块**自己**切成两组：
//   组 0 管低半区（逻辑地址 0..511）、组 1 管高半区（512..1023）：组号 = 地址最高位。
// 每组 13 块 × (512 字 × 20 位)，13 × 20 = 260 ≥ 256 → 用 256 位，余 4 位空着。
// 这样切的**关键性质**：两个半区各有独立的读写口，可以同拍各读一个字（每拍 2 字），
// 代价是"同拍两个字"必须一高一低（相邻地址凑不出来，布局侧要把成对读的字摆到两个半区）。
//
// ------------------------------ 一个必须知道的物理约束 ------------------------------
// 每块 RAM10 的写使能粒度是 10 位（20 位宽配两位 WE），**不是 128 位**。所以"只写低半字
// 16 字节"做不到位级掩码。C16 那种半字写由 ngm_result_former 用共用的 16 字节暂存寄存器
// 把相邻两拍配成整字之后再整字写进来；本模块只认整字写（见该模块头部的说明）。
//
// ------------------------------ 接口约定（四片共用，控制器必须遵守）------------------------------
//   · 读：每拍 2 次，**0 号口读低半区、1 号口读高半区**，各给组内索引（半区 = 逻辑地址 bit9，
//     索引 = 逻辑地址 bit8:0；这个拆分只是连线，在控制器里免费得到）。读延迟 1 拍
//     （OUTPUT_REG=0）。哪一拍读由控制器的 rd_valid 决定。
//   · 写：每拍 2 次，0 号口写低半区、1 号口写高半区，整字 256 位。
//   · 口与半区的固定对应关系是**故意**的：写成 (逻辑地址) 口的话，本模块就得加两个 256 位的
//     回程多路选择器（约 512 个 LUT）白花面积；固定对应之后，同拍读/写落在同一半区的冲突
//     由控制器在生成地址时就避免（它本来就要算地址落在哪个半区）。
//   · RAM 内容不复位（上电是随机的），整帧数据由写入路径灌满；控制器复位有效位，RAM及返回数据均不复位。
// ============================================================================
module ngm_act_ram #(                 // 激活存储一片：参数（四片同一份代码，只是例化两次/四次）
    parameter int unsigned ADDR_W = 10,                       // 逻辑地址位宽：1024 字 → 10 位
    parameter int unsigned WORD_W = 256,                      // 逻辑字宽：32 个 INT8 = 256 位
    parameter int unsigned BLK_W  = 20,                       // 每块 RAM10 的读写宽度：20 位（512 深 = 10 Kbit 正好一块）
    parameter int unsigned BLK_N  = 13,                       // 一组的块数：ceil(256/20) = 13
    parameter int unsigned GRP_N  = 2,                        // 组数：固定 2（低半区 / 高半区）
    parameter int unsigned IDX_W  = ADDR_W - 1                // 组内索引位宽：512 字 → 9 位
) ( // 参数结束，接口开始。
    input  logic                    clk,                      // 时钟
    input  logic                    reset,                    // 公共复位接口；本模块不复位RAM或读返回。

    // ------------------------------ 读口（0 号读低半区、1 号读高半区）------------------------------
    input  wire [GRP_N-1:0]         rd_valid,                 // 第 i 组这一拍有没有读请求
    input  wire [IDX_W-1:0]         rd_idx [GRP_N],           // 第 i 组的组内索引（512 字内）
    output wire [WORD_W-1:0]        rd_data [GRP_N],          // 第 i 组的读回数据（1 拍后有效）

    // ------------------------------ 写口（0 号写低半区、1 号写高半区）------------------------------
    input  wire [GRP_N-1:0]         wr_valid,                 // 第 i 组这一拍有没有写请求
    input  wire [IDX_W-1:0]         wr_idx [GRP_N],           // 第 i 组的组内写地址
    input  wire [WORD_W-1:0]        wr_data [GRP_N]           // 第 i 组要写的整字
);                                                            // 端口结束
    // ------------------------------ 常量 ------------------------------

    // ------------------------------ 存储本体：2 组 × 13 块 ------------------------------
    logic [BLK_W-1:0] blk_rd [GRP_N][BLK_N];                  // [组][块] 的读回数据（1 拍后有效）

    for (genvar g = 0; g < GRP_N; g = g + 1) begin : g_grp     // 逐组例化
        for (genvar b = 0; b < BLK_N; b = b + 1) begin : g_blk // 逐块例化（一个 RAM10 = 512×20）
            // 显式例化 EFX_RAM10：512 深 × 20 位 = 10 Kbit，正好一块；OUTPUT_REG=0 → 读延迟 1 拍。
            EFX_RAM10 #(                                      // 易灵思 10Kbit 块 RAM
                .READ_WIDTH  (BLK_W),                          // 读宽度 20 位
                .WRITE_WIDTH (BLK_W),                          // 写宽度 20 位
                .OUTPUT_REG  (1'b0),                           // 输出不再打一拍 → 读延迟 1 拍
                .WRITE_MODE  ("READ_FIRST")                    // 同址读写读旧值（本设计的读写不同址）
            ) u_blk (                                          // 本块实例
                .WCLK    (clk),                                // 写时钟：与全设计同钟
                .WE      (2'b11),                              // 20 位宽的两段写使能都给上（整块写）
                .WCLKE   (wr_valid[g]),                        // 本组的写使能（口↔组固定对应）
                .WADDREN (1'b1),                               // 写地址使能常开
                .WDATA   (wr_data[g] >> (b * BLK_W)),          // 本块要写的 20 位：从整字里切出来（高块补零无害）
                .WADDR   (wr_idx[g]),                          // 本块的写地址（组内索引）
                .RCLK    (clk),                                // 读时钟：与全设计同钟
                .RE      (rd_valid[g]),                               // RE为零时原生保持读地址与返回，独立写口仍可工作。
                .RST     (1'b0),                               // 读输出寄存器不复位（纯数据寄存器，省一片复位网）
                .RADDREN (1'b1),                               // 读地址使能常开
                .RDATA   (blk_rd[g][b]),                       // 本块读回数据
                .RADDR   (rd_idx[g])                           // 本组的读地址（组内索引）
            );                                                 // 本块实例结束
        end                                                    // 逐块结束

        // 把 13 块拼回 256 位：前 12 块各 20 位（共 240），最后一块只取低 16 位（240+16 = 256）。
        // 用 generate 逐块连续赋值（每块的位宽都是常量），不写运行时循环 —— 运行时的变位宽切片不合法。
        for (genvar b2 = 0; b2 < BLK_N; b2 = b2 + 1) begin : g_join // 逐块拼回整字
            if ((b2 + 1) * BLK_W <= WORD_W) begin                   // 本块的 20 位整块都落在 256 位内
                assign rd_data[g][b2*BLK_W +: BLK_W] = blk_rd[g][b2]; // 整块搬过去
            end else begin                                          // 最后一块只放得下一部分
                assign rd_data[g][b2*BLK_W +: (WORD_W - b2*BLK_W)]  // 只取还装得下的那几位
                     = blk_rd[g][b2][(WORD_W - b2*BLK_W)-1:0];      // 低位对齐（块的高 4 位丢弃）
            end                                                     // 拼法结束
        end                                                         // 逐块拼回结束
    end                                                         // 逐组结束

endmodule // 激活RAM结束。


