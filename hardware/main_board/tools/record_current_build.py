"""Record a fresh, timing-clean and PGM-verified artifact."""
from pathlib import Path
import argparse,copy,hashlib,json,re,os
import xml.etree.ElementTree as ET
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--bit',required=True,type=Path,help='bitstream generated by this PGM run')
parser.add_argument('--hex',required=True,type=Path,help='HEX image generated by this PGM run')
parser.add_argument('--pgm',required=True,type=Path,help='fresh PGM verification output from this run')
parser.add_argument('--pgm-log',required=True,type=Path,help='efx_run PGM log proving file-generation flow passed')
parser.add_argument('--rom-verification',required=True,type=Path,help='verify_firmware_rom JSON for this map/PGM run')
parser.add_argument('--out-dir',type=Path,default=Path('outflow'),help='directory containing this run’s PnR reports')
parser.add_argument('--map-dir',type=Path,default=Path('outflow'),help='directory containing the fresh mapped netlist')
parser.add_argument('--project-xml',type=Path,default=Path('ti60f225_oob.xml'),help='XML carrying the seed used by this PnR run')
args=parser.parse_args()
def project_path(path):return path if path.is_absolute() else root/path
bit_path=project_path(args.bit).resolve()
hex_path=project_path(args.hex).resolve()
pgm_path=project_path(args.pgm).resolve()
pgm_log_path=project_path(args.pgm_log).resolve()
rom_verify_path=project_path(args.rom_verification).resolve()
out_dir=project_path(args.out_dir).resolve()
map_dir=project_path(args.map_dir).resolve()
project_xml=project_path(args.project_xml).resolve()
map_path=(map_dir/'ti60f225_oob.map.v').resolve()
pnr_path=(out_dir/'ti60f225_oob.route.rpt.xml').resolve()
timing_path=(out_dir/'ti60f225_oob.timing.rpt').resolve()
for path in (bit_path,hex_path,pgm_path,pgm_log_path,rom_verify_path,map_path,pnr_path,timing_path):
    if not path.is_file():raise SystemExit(f'Missing current-build artifact: {path}')
if pgm_path.stat().st_mtime_ns < map_path.stat().st_mtime_ns:
    raise SystemExit('PGM artifact predates the current mapped netlist')
if pnr_path.stat().st_mtime_ns < map_path.stat().st_mtime_ns:
    raise SystemExit('PnR route artifact predates the current mapped netlist')
if timing_path.stat().st_mtime_ns < pnr_path.stat().st_mtime_ns:
    raise SystemExit('Timing report predates current PnR route artifact')
if bit_path.stat().st_mtime_ns < pnr_path.stat().st_mtime_ns:
    raise SystemExit('Bitstream predates the current PnR route artifact')
if hex_path.stat().st_mtime_ns < pnr_path.stat().st_mtime_ns:
    raise SystemExit('HEX image predates the current PnR route artifact')
if rom_verify_path.stat().st_mtime_ns < map_path.stat().st_mtime_ns or rom_verify_path.stat().st_mtime_ns < pgm_path.stat().st_mtime_ns:
    raise SystemExit('ROM/PGM verification predates the current map or PGM output')
pgm_log=pgm_log_path.read_text(encoding='utf-8',errors='ignore')
if not re.search(r'(?im)^\s*pgm\s*:\s*PASS\s*$',pgm_log):
    raise SystemExit('PGM log does not contain an explicit efx_run PGM PASS result')
if pgm_log_path.stat().st_mtime_ns < pnr_path.stat().st_mtime_ns:
    raise SystemExit('PGM log predates the current PnR route artifact')
report=timing_path.read_text(encoding='utf-8')
part=report.split('---------- 2. Clock Relationship Summary (begin) ----------')[1].split('Clock Relationship Summary (end)')[0]
setup,hold=part.split('Hold (Min) Clock Relationship')
def slacks(text):return [float(x) for x in re.findall(r'^\S+\s+\S+\s+[-.0-9]+\s+([-.0-9]+)\s+\(',text,re.M)]
sv,hv=slacks(setup),slacks(hold)
if not sv or not hv:raise SystemExit('Cannot parse final setup/hold summary')
if min(sv)<0 or min(hv)<0:raise SystemExit('Refusing to publish a timing-failing candidate')
p=root/'CURRENT_PROJECT.json';data=json.loads(p.read_text(encoding='utf-8'))
sha=lambda b:hashlib.sha256(b).hexdigest()
bit=bit_path.read_bytes()
hex_image=hex_path.read_bytes()
firmware=(root/'software/build/product_ui_24k.bin').read_bytes()
ocr=(root/'software/artifacts/product_ui_24k_ocr_padded.bin').read_bytes()
rom_verify=json.loads(rom_verify_path.read_text(encoding='utf-8'))
if rom_verify.get('raw_bin_sha256')!=sha(firmware):raise SystemExit('ROM verification raw BIN hash does not match current firmware')
if rom_verify.get('ocr_sha256')!=sha(ocr):raise SystemExit('ROM verification OCR image hash does not match current image')
if rom_verify.get('model_count')!=29 or len(rom_verify.get('lanes',[]))!=12:
    raise SystemExit('ROM verification does not prove all 29 models and 12 lane inputs')
lane_by_name={Path(row['file']).name:row['sha256'] for row in rom_verify['lanes']}
for lane_path in root.glob('EfxSapphireSoc.v_toplevel_system_ramA_logic_ram_symbol*.bin'):
    if lane_by_name.get(lane_path.name)!=sha(lane_path.read_bytes()):
        raise SystemExit(f'ROM verification lane mismatch: {lane_path.name}')
prior_deployment=copy.deepcopy({k:data[k] for k in ('latest_bit','bit_sha256','bit_bytes','latest_status','jtag_program',
                                                    'asset_bundle','runtime_check','visual_acceptance') if k in data})
source_paths={project_xml,out_dir/'ti60f225_oob.lpf',root/'ti60f225_oob.xml',root/'ti60f225_oob.sdc',root/'ti60f225_oob.peri.xml',root/'sources.f',
              root/'compile.bat',root/'software/build_24k.bat',root/'software/build_multi_style_24k.bat',
              root/'software/diag_link.ld',root/'software/pack_24k_lanes.py',
              root/'tools/update_firmware_rom.py',root/'tools/verify_firmware_rom.py',
              root/'tools/record_current_build.py',root/'tools/audit_firmware_counter_csrs.py'}
source_paths.update(root/line.strip() for line in (root/'sources.f').read_text(encoding='utf-8').splitlines() if line.strip())
source_paths.update(p for p in (root/'software').glob('*') if p.suffix.lower() in {'.c','.h','.s'})
source_paths.update(root.glob('EfxSapphireSoc.v_toplevel_system_ramA_logic_ram_symbol*.bin'))
source_rows=[]
for path in sorted(source_paths,key=lambda q:q.relative_to(root).as_posix()):
    if not path.is_file():raise SystemExit(f'Missing source input: {path}')
    rel=path.relative_to(root).as_posix()
    source_rows.append((rel,sha(path.read_bytes())))
source_digest=sha(''.join(f'{rel}\0{digest}\n' for rel,digest in source_rows).encode('utf-8'))
route_xml=ET.parse(pnr_path).getroot()
ns={'efx':'http://www.efinixinc.com/tool_report'}
route_values={entry.attrib['name']:entry.attrib['value'] for entry in route_xml.findall('.//efx:group_data',ns)}
def used(name):
    value=route_values.get(name,'')
    match=re.match(r'\s*([0-9,]+)\s*/',value)
    return int(match.group(1).replace(',','')) if match else None
data.update(latest_bit=bit_path.relative_to(root).as_posix(),bit_sha256=sha(bit),bit_bytes=len(bit),
            bitstream=bit_path.relative_to(root).as_posix(),status='compiled_signoff_pass_not_programmed',
            latest_hex=hex_path.relative_to(root).as_posix(),hex_sha256=sha(hex_image),hex_bytes=len(hex_image),
            firmware_sha256=sha(firmware),firmware_bytes=len(firmware),
            ocr_image_sha256=sha(ocr),ocr_image_bytes=len(ocr),source_sha256=source_digest,
            source_file_count=len(source_rows),setup_wns_ns=min(sv),hold_whs_ns=min(hv),board_tested=False)
rom_lane_files=sorted(root.glob('EfxSapphireSoc.v_toplevel_system_ramA_logic_ram_symbol*.bin'))
if len(rom_lane_files)!=12:raise SystemExit(f'Expected 12 project-root OCR lane inputs, found {len(rom_lane_files)}')
data['embedded_firmware']={
    'raw_bin_sha256':sha(firmware),'raw_bin_bytes':len(firmware),
    'ocr_image_sha256':sha(ocr),'ocr_image_bytes':len(ocr),
    'lane_inputs':[{'path':p.relative_to(root).as_posix(),'sha256':sha(p.read_bytes()),'bytes':p.stat().st_size}
                   for p in rom_lane_files],
    'readmemh_source':'rtl/soc/soc.v; relative lane paths resolved from compile.bat project-root cwd',
}
data['final_resources']={'XLR':used('XLRs'),'RAM10':used('Memory Blocks'),'DSP48':used('DSP Blocks'),'clocks':used('Clocks')}
map_rows=(root/'outflow/ti60f225_oob.res.csv').read_text(encoding='utf-8').splitlines()
top_line=next((line for line in map_rows if line.startswith('ti60f225_oob_top:ti60f225_oob_top')),None)
if top_line is None:raise SystemExit('Cannot find top-level map resource row')
map_nums=[int(value) for value in re.findall(r'(?<!\d)(\d+)\(\d+\)',top_line)]
if len(map_nums)<7:raise SystemExit('Cannot parse top-level map resource row')
data['source_map_resources']={'LUT4':map_nums[3],'FF':map_nums[0],'SRL8':map_nums[1],
                              'RAM10':map_nums[5],'DSP48':map_nums[6]}
seed_match=re.search(r'<efx:param name="seed" value="(\d+)"',
                     project_xml.read_text(encoding='utf-8'))
if not seed_match:raise SystemExit('Cannot read PnR seed from project XML')
seed=int(seed_match.group(1))
data['build_configuration']={'synthesis_mode':'speed2','seq_opt':1,'retiming':0,
                             'pnr_optimization':ET.parse(project_xml).getroot().find("{http://www.efinixinc.com/enf_proj}place_and_route/{http://www.efinixinc.com/enf_proj}param[@name='optimization_level']").attrib['value'],'placer_effort_level':5,
                             'seed':seed,'max_threads':int(os.environ.get('EFX_MAX_THREADS','4')),
                             'route_internal_max_iterations':int(os.environ.get('EFX_ROUTE_ITERATIONS','190'))}
timing_pass=min(sv)>=0 and min(hv)>=0
data['latest_status']='CANDIDATE; STA_PASS; PGM_PASS; not board-tested'
data['bit_matches_source']=True
data['source_status']='BIT generated from current sources; fresh map/PnR/STA/PGM verified; not board-tested'
data['previous_deployment']=prior_deployment
data['deployment_status']='NEW_BIT_NOT_PROGRAMMED; previous deployment and Flash readback retained in previous_deployment'
data['jtag_program']={'status':'NOT_PROGRAMMED','bit_sha256':sha(bit)}
assets=json.loads((root/'assets/catalog_manifest.json').read_text(encoding='utf-8'))
bundle_path=root/assets['bundle_file'] if str(assets['bundle_file']).startswith('assets/') else root/'assets'/assets['bundle_file']
bundle=bundle_path.read_bytes()
if len(bundle)!=assets['bundle_bytes'] or sha(bundle)!=assets['bundle_sha256']:
    raise SystemExit('Current model bundle differs from asset manifest')
if len(assets['models'])!=rom_verify['model_count']:
    raise SystemExit('Model bundle count differs from embedded firmware')
data['asset_bundle']={'path':bundle_path.relative_to(root).as_posix(),
    'bytes':len(bundle),'sha256':sha(bundle),
    'crc16_ccitt_false':assets['bundle_crc16_ccitt_false'],
    'flash_base':assets['bundle_layout']['flash_base'],
    'model_count':len(assets['models']),'lut_count':len(assets['lut_order']),
    'validated_for_bit_sha256':sha(bit),
    'candidate_flash_write':'NONE; new bundle not written; no Flash write performed'}
data['timing_report']=timing_path.relative_to(root).as_posix()
data['pgm_artifact']=pgm_path.relative_to(root).as_posix()
data['pgm_sha256']=sha(pgm_path.read_bytes())
data['pgm_bytes']=pgm_path.stat().st_size
data['pgm_log']=pgm_log_path.relative_to(root).as_posix()
data['pgm_log_sha256']=sha(pgm_log_path.read_bytes())
data['rom_verification']=rom_verify_path.relative_to(root).as_posix()
data['mapped_netlist']={'path':map_path.relative_to(root).as_posix(),'sha256':sha(map_path.read_bytes())}
data['pnr_project_xml']=project_xml.relative_to(root).as_posix()
data['candidate_evidence']=out_dir.relative_to(root).as_posix()
data['timing_candidates']=[entry for entry in data.get('timing_candidates',[])
                           if not (entry.get('seed')==seed and entry.get('path')==bit_path.relative_to(root).as_posix())]
data['timing_candidates'].append({'seed':seed,'status':'TIMING_PASS; PGM_PASS; NOT_PROGRAMMED',
                                  'path':bit_path.relative_to(root).as_posix(),'bit_sha256':sha(bit),
                                  'setup_wns_ns':min(sv),'hold_whs_ns':min(hv),
                                  'map_vdb_sha256':sha((map_dir/'ti60f225_oob.vdb').read_bytes())})
p.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(data['latest_status'],data['setup_wns_ns'],data['hold_whs_ns'],data['latest_bit'],data['bit_sha256'])
